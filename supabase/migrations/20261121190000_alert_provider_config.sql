-- User-configurable email providers for individual Alert nodes.
-- API keys are stored encrypted in Supabase Vault, never in localStorage or in
-- the workflow JSON. Only the service role can reach these objects; anon and
-- authenticated are explicitly revoked because SECURITY DEFINER functions in
-- public are executable by PUBLIC unless stated otherwise.

begin;

create table if not exists public.alert_provider_config (
  owner_wallet text not null,
  node_id text not null default 'legacy',
  provider text not null default 'resend',
  from_email text not null default '',
  secret_name text not null,
  updated_at timestamptz not null default now()
);

-- Existing wallet-level rows become the legacy node of that wallet. New rows
-- are keyed by an explicit, stable node id generated by the canvas.
alter table public.alert_provider_config add column if not exists node_id text;
update public.alert_provider_config
set node_id = 'legacy'
where node_id is null or trim(node_id) = '';
alter table public.alert_provider_config alter column node_id set not null;
alter table public.alert_provider_config alter column node_id set default 'legacy';

alter table public.alert_provider_config drop constraint if exists alert_provider_config_pkey;
alter table public.alert_provider_config add primary key (owner_wallet, node_id);

alter table public.alert_provider_config enable row level security;
revoke all on public.alert_provider_config from anon, authenticated;
grant all on public.alert_provider_config to service_role;

-- Replace the old wallet-level RPC signatures. Keeping them would allow a
-- caller to read or write a config without naming the node that owns it.
drop function if exists public.save_alert_provider_config(text, text, text, text);
drop function if exists public.get_alert_provider_config(text);
drop function if exists public.get_alert_provider_status(text);

create or replace function public.save_alert_provider_config(
  p_owner_wallet text,
  p_node_id text,
  p_provider text,
  p_api_key text,
  p_from_email text
) returns void
language plpgsql
security definer
set search_path = public, vault
as $$
declare
  v_owner text := lower(trim(coalesce(p_owner_wallet, '')));
  v_node text := trim(coalesce(p_node_id, ''));
  v_provider text := lower(trim(coalesce(p_provider, 'resend')));
  v_name text;
  v_existing_provider text;
  v_id uuid;
begin
  if length(v_owner) < 10 then
    raise exception 'owner_wallet required';
  end if;
  if v_node = '' or length(v_node) > 120 or v_node !~ '^[A-Za-z0-9_-]+$' then
    raise exception 'node_id required';
  end if;
  if v_provider not in ('resend', 'sendgrid', 'postmark') then
    raise exception 'unsupported provider';
  end if;

  v_name := 'alert_' || v_provider || '_' || md5(v_owner || ':' || v_node);

  if p_api_key is null or length(trim(p_api_key)) < 8 then
    -- No new key: keep the existing encrypted secret and provider. This lets
    -- the user update only the sender without re-entering credentials.
    select secret_name, provider into v_name, v_existing_provider
    from public.alert_provider_config
    where owner_wallet = v_owner and node_id = v_node;
    if v_name is null then
      raise exception 'api_key required';
    end if;
    if coalesce(v_existing_provider, 'resend') <> v_provider then
      raise exception 'changing provider requires a new api_key';
    end if;
  else
    select id into v_id from vault.secrets where name = v_name;
    if v_id is null then
      perform vault.create_secret(trim(p_api_key), v_name, 'Alert node API key');
    else
      perform vault.update_secret(v_id, trim(p_api_key), v_name, 'Alert node API key');
    end if;
  end if;

  insert into public.alert_provider_config (owner_wallet, node_id, provider, from_email, secret_name, updated_at)
  values (
    v_owner,
    v_node,
    v_provider,
    coalesce(trim(p_from_email), ''),
    v_name,
    now()
  )
  on conflict (owner_wallet, node_id) do update
    set provider = excluded.provider,
        from_email = excluded.from_email,
        secret_name = excluded.secret_name,
        updated_at = now();
end $$;

create or replace function public.get_alert_provider_config(
  p_owner_wallet text,
  p_node_id text
)
returns table(provider text, api_key text, from_email text)
language plpgsql
security definer
set search_path = public, vault
as $$
begin
  return query
  select c.provider, s.decrypted_secret, c.from_email
  from public.alert_provider_config c
  join vault.decrypted_secrets s on s.name = c.secret_name
  where c.owner_wallet = lower(trim(p_owner_wallet))
    and c.node_id = trim(p_node_id);
end $$;

create or replace function public.get_alert_provider_status(
  p_owner_wallet text,
  p_node_id text
)
returns table(provider text, from_email text, configured boolean, updated_at timestamptz)
language plpgsql
security definer
set search_path = public, vault
as $$
begin
  return query
  select c.provider, c.from_email, (s.id is not null), c.updated_at
  from public.alert_provider_config c
  left join vault.secrets s on s.name = c.secret_name
  where c.owner_wallet = lower(trim(p_owner_wallet))
    and c.node_id = trim(p_node_id);
end $$;

revoke all on function public.save_alert_provider_config(text, text, text, text, text) from public, anon, authenticated;
revoke all on function public.get_alert_provider_config(text, text) from public, anon, authenticated;
revoke all on function public.get_alert_provider_status(text, text) from public, anon, authenticated;

grant execute on function public.save_alert_provider_config(text, text, text, text, text) to service_role;
grant execute on function public.get_alert_provider_config(text, text) to service_role;
grant execute on function public.get_alert_provider_status(text, text) to service_role;

commit;
